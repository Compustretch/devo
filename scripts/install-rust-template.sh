#!/usr/bin/env bash
# Installs the default Rust app template into internal/project/embedded_templates/rust.
#
# Usage, from the repo root:   bash scripts/install-rust-template.sh
#        or from anywhere:     bash /path/to/install-rust-template.sh /path/to/devo-repo
#
# It reports every decision it makes (written / unchanged / moved / not present),
# lists the template directory before and after, and names the exact line if
# anything fails. Nothing is deleted: replaced or removed files are MOVED to
# ~/.devo-template-backup/<timestamp>/. Safe to run more than once.
set -Eeuo pipefail

say() { printf 'install-rust-template: %s\n' "$*"; }
trap 'printf "install-rust-template: FAILED at line %s: %s\n" "$LINENO" "$BASH_COMMAND" >&2' ERR

# The repo is the directory you run this from (or the path you pass), NOT where
# this script file happens to be.
repo="$(cd "${1:-$PWD}" && pwd)"
tpl="$repo/internal/project/embedded_templates/rust"
backup="$HOME/.devo-template-backup/$(date +%Y%m%d-%H%M%S)"

say "starting"
say "repo:     $repo"
say "template: $tpl"

if [ ! -f "$repo/go.mod" ] || [ ! -d "$tpl" ]; then
  say "STOP: this doesn't look like the devo source repo." >&2
  say "  need a go.mod in $repo and a directory $tpl" >&2
  say "  run from the repo root (the directory containing cmd/ and internal/), or pass its path" >&2
  exit 1
fi

list() { (cd "$tpl" && find . -type f -exec ls -l {} + | sed 's/^/    /' | sort -k9); }

say "template files BEFORE:"
list

# stash <relative path>: move an existing template file into the backup dir.
stash() {
  local rel=$1
  if [ ! -e "$tpl/$rel" ]; then
    say "not present  $rel"
    return 0
  fi
  mkdir -p "$backup/$(dirname "$rel")"
  mv "$tpl/$rel" "$backup/$rel"
  say "MOVED        $rel  ->  $backup/$rel"
}

# install_file <relative path>: write stdin to the template. Reports whether it
# wrote, found the file already correct, or backed up different content first.
install_file() {
  local rel=$1 dest="$tpl/$1" new
  new="$(mktemp)"
  cat > "$new"
  if [ -e "$dest" ] && cmp -s "$new" "$dest"; then
    rm -f "$new"
    say "unchanged    $rel (already correct)"
    return 0
  fi
  if [ -s "$dest" ]; then
    say "existing $rel has different content; backing it up first"
    stash "$rel"
  fi
  mkdir -p "$(dirname "$dest")"
  cat "$new" > "$dest"
  rm -f "$new"
  say "WROTE        $rel ($(wc -c < "$dest" | tr -d ' ') bytes)"
}

say "removing files that must not be in a template (devo generates devo.yaml and"
say "compose.yaml itself; .go files break the build) and un-suffixed originals:"
for f in tmpl.go devo.yaml devo.yaml.tmpl compose.yaml compose.yaml.tmpl \
         Cargo.toml Dockerfile README.md src/main.rs; do
  stash "$f"
done

say "writing template files:"

install_file Cargo.toml.tmpl <<'EOF'
[package]
name = "{{project_name}}"
version = "0.1.0"
edition = "2021"

[dependencies]
EOF

install_file src/main.rs.tmpl <<'EOF'
fn main() {
    println!("Hello from {{project_name}}!");
}
EOF

install_file Dockerfile.tmpl <<'EOF'
FROM rust:1 AS build
WORKDIR /app
COPY . .
RUN cargo build --release

FROM debian:bookworm-slim
COPY --from=build /app/target/release/{{project_name}} /usr/local/bin/app
CMD ["app"]
EOF

install_file .gitignore <<'EOF'
/target
EOF

install_file README.md.tmpl <<'EOF'
# {{project_name}}

Scaffolded with [devo](https://github.com/Compustretch/devo).

## Run

```bash
cargo run
```

## Local services

```bash
devo services          # see what's available and what's enabled
devo add postgres      # enable a service
devo dev               # start the local stack
devo down              # stop it
```

Enabled services are listed in `devo.yaml`. `compose.yaml` and the files under
`platform/` are generated by devo; edit `devo.yaml` instead of editing them.
EOF

# CI runs the unit tests only (--bins). The generated smoke tests in tests/ need
# the local service stack, which CI doesn't start.
install_file .github/workflows/ci.yml <<'EOF'
name: ci

on:
  push:
  pull_request:

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: dtolnay/rust-toolchain@stable
      - run: cargo build --release
      - run: cargo test --bins
EOF

say "template files AFTER:"
list

empty="$(cd "$tpl" && find . -type f -empty)"
if [ -n "$empty" ]; then
  say "STOP: these template files are still empty:" >&2
  printf '    %s\n' $empty >&2
  exit 1
fi
say "check: no empty files in the template"

say "running: go test ./internal/project/ (template soundness check)"
(cd "$repo" && go test ./internal/project/)

if [ -d "$backup" ]; then
  say "DONE. Replaced/removed files were moved to: $backup"
else
  say "DONE. Nothing needed backing up."
fi